#!/usr/bin/env python3
"""解析官方样题 -> seed-questions.json（含手写补充题）"""
import re, json, os

text = open('/tmp/sample_exam.txt', encoding='utf-8').read()
lines = text.split('\n')

q_start = next(i for i, l in enumerate(lines) if '一、单选题' in l)
q_end = next(i for i, l in enumerate(lines) if '二、实操题' in l)
a_start = next(i for i, l in enumerate(lines) if '参考答案' in l)

# ---- 答案 ----
answers = {}
ans_zone = '\n'.join(lines[a_start:])
for m in re.finditer(r'(\d+)\.\s*([A-D])', ans_zone):
    answers[int(m.group(1))] = m.group(2)

# ---- 题目 ----
ques, cur, expect_next = [], None, 1
for ln in lines[q_start + 1:q_end]:
    mq = re.match(r'^\s*(\d+)\.\s*(.*)', ln)
    mo = re.match(r'^\s*([A-D])\.\s*(.*)', ln)
    if mq and not mo:
        num = int(mq.group(1))
        if num == expect_next:
            cur = {'num': num, 'stem': mq.group(2).strip(), 'options': []}
            ques.append(cur)
            expect_next += 1
            continue
    if mo and cur is not None:
        cur['options'].append(mo.group(2).strip())
        continue
    if cur is not None:
        s = ln.strip()
        if s and s != '( )' and s != '(   )':
            if cur['options']:
                cur['options'][-1] += ' ' + s
            else:
                cur['stem'] += s

# 官方样题逐题模块映射：以《标准》职业功能归属为准（非样题出现顺序）
OFFICIAL_MODULE = {}
for n in range(1, 15): OFFICIAL_MODULE[n] = '数字人专项'        # Q1-14 数字人工种知识
OFFICIAL_MODULE[16] = '数字人专项'                                # Q16 体感交互（工种交互语境）
OFFICIAL_MODULE[15] = '数据处理与标注'                            # Q15 文本预处理：标注分词、句法判别
for n in (19, 20, 21, 22): OFFICIAL_MODULE[n] = '数据处理与标注'  # Q19-22 预处理/特征工程/视觉存储
for n in range(31, 39): OFFICIAL_MODULE[n] = '数据处理与标注'     # Q31-38 清洗与标注
for n in (17, 18, 23, 24, 25, 26, 27, 28, 29, 30): OFFICIAL_MODULE[n] = '业务分析'
for n in (39, 40, 44, 45): OFFICIAL_MODULE[n] = '智能系统设计'
for n in (41, 42, 43): OFFICIAL_MODULE[n] = '智能训练'

def module_of(n):
    return OFFICIAL_MODULE.get(n, '智能系统设计')

official = []
for q in ques:
    stem = re.sub(r'\s*\(\s*\)\s*$', '', q['stem']).strip()
    official.append({
        'type': 'single', 'module': module_of(q['num']), 'stem': stem,
        'options': q['options'], 'answer': answers[q['num']],
        'explanation': '', 'difficulty': 2, 'source': '官方样题',
    })

assert len(official) == 45, f'官方题数不对: {len(official)}'
for q in official:
    assert len(q['options']) == 4, q['stem'][:30]
    assert q['answer'] in 'ABCD', q

